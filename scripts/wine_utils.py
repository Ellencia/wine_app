GENERIC = ("블랜드", "블렌드", "블랜딩", "블렌딩")


def variety_tags(varieties):
    tags = []
    for part in (varieties or "").split(","):
        s = re.sub(r"\([^)]*\)", "", part)          # (편암), (토착품종) 제거
        s = re.sub(r"\d+(\.\d+)?\s*%", "", s)        # 비율 제거
        s = re.sub(r"\s*이상", "", s)
        s = re.sub(r"\s외(\s|$).*$", "", s)           # "산지오베제 외 레드 블랜드" -> 산지오베제
        s = re.sub(r"\s+", " ", s).strip()
        s = re.sub(r"\s*등$", "", s)
        if not s or any(g in s for g in GENERIC):    # "화이트 블랜드" 같은 총칭은 태그 없음
            continue
        s = SYNONYMS.get(s, s)
        if s not in tags:
            tags.append(s)
    return tags
